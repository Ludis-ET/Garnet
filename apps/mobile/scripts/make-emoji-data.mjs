// Builds src/features/emoji/emojiData.ts from Unicode's emoji-test.txt (Unicode License v3).
// Usage: node scripts/make-emoji-data.mjs <path/to/emoji-test.txt>
// Get the file from https://unicode.org/Public/emoji/<version>/emoji-test.txt. The board then
// lists every fully-qualified emoji in the iPhone keyboard's categories, with names for search,
// and marks the emoji that take a skin tone (by the simple rule the board applies at runtime).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [source] = process.argv.slice(2);
if (source === undefined) {
  process.stderr.write("Usage: node scripts/make-emoji-data.mjs <emoji-test.txt>\n");
  process.exit(1);
}
const text = readFileSync(source, "utf8");
const version = /^# Version: ([\d.]+)/m.exec(text)?.[1] ?? /emoji\/([\d.]+)\//.exec(text)?.[1];

// The iPhone keyboard's categories, in its order (Smileys & People merges two Unicode groups).
const CATEGORIES = [
  { id: "people", title: "Smileys & People", groups: ["Smileys & Emotion", "People & Body"] },
  { id: "nature", title: "Animals & Nature", groups: ["Animals & Nature"] },
  { id: "food", title: "Food & Drink", groups: ["Food & Drink"] },
  { id: "activity", title: "Activity", groups: ["Activities"] },
  { id: "travel", title: "Travel & Places", groups: ["Travel & Places"] },
  { id: "objects", title: "Objects", groups: ["Objects"] },
  { id: "symbols", title: "Symbols", groups: ["Symbols"] },
  { id: "flags", title: "Flags", groups: ["Flags"] },
];
const TONES = [0x1f3fb, 0x1f3fc, 0x1f3fd, 0x1f3fe, 0x1f3ff];
const FE0F = 0xfe0f;

const byGroup = new Map();
const all = new Set();
let group = "";
for (const line of text.split("\n")) {
  const g = /^# group: (.+)$/.exec(line);
  if (g) {
    group = g[1].trim();
    continue;
  }
  const m = /^([0-9A-F ]+);\s*fully-qualified\s*#\s*\S+\s+E[\d.]+\s+(.+)$/.exec(line);
  if (!m) continue;
  const cps = m[1]
    .trim()
    .split(/\s+/)
    .map((h) => parseInt(h, 16));
  const emoji = String.fromCodePoint(...cps);
  all.add(emoji);
  if (cps.some((c) => TONES.includes(c))) continue; // tones are offered on long-press instead
  if (!byGroup.has(group)) byGroup.set(group, []);
  byGroup.get(group).push({ cps, emoji, name: m[2].trim() });
}

/** The board's rule: the tone goes right after the first code point (dropping its FE0F). */
function withTone(cps, tone) {
  const rest = cps[1] === FE0F ? cps.slice(2) : cps.slice(1);
  return String.fromCodePoint(cps[0], tone, ...rest);
}

const out = CATEGORIES.map((c) => {
  const rows = c.groups.flatMap((g) => byGroup.get(g) ?? []);
  const lines = rows.map((r) => {
    const toned = TONES.every((t) => all.has(withTone(r.cps, t)));
    // "|" never appears in emoji names; names are lower-cased for search.
    return `${r.emoji}|${r.name.toLowerCase().replace(/\|/g, " ")}${toned ? "|t" : ""}`;
  });
  return { ...c, lines };
});

const total = out.reduce((n, c) => n + c.lines.length, 0);
const file = `// Generated by scripts/make-emoji-data.mjs from Unicode emoji-test.txt (Emoji ${version ?? "?"}).
// Do not edit by hand. Unicode data: © Unicode, Inc., used under the Unicode License v3
// (https://www.unicode.org/license.txt). ${String(total)} emoji, without skin-tone variants.

/** One line per emoji: "emoji|name" plus "|t" when it takes a skin tone. */
export const EMOJI_SOURCE: readonly { id: string; title: string; data: string }[] = [
${out.map((c) => `  {\n    id: "${c.id}",\n    title: "${c.title}",\n    data: \`\n${c.lines.join("\n")}\n\`,\n  },`).join("\n")}
];
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../src/features/emoji/emojiData.ts");
writeFileSync(target, file);
process.stdout.write(
  `Wrote ${String(total)} emoji in ${String(out.length)} categories to ${target}
`,
);
